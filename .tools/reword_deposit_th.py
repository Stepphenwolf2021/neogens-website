def main():
    s = TARGET.read_text(encoding="utf-8")
    before = s.count("ฝาก")
    used = 0

    for old, new in PAIRS:
        n = s.count(old)
        if n == 0:
            sys.exit(f"[abort] ไม่พบข้อความ: {old[:60]}")
        s = s.replace(old, new)
        used += n

    TARGET.write_text(s, encoding="utf-8")
    after = s.count("ฝาก")
    print(f"  แทนที่ {used} จุด · คำว่า ฝาก เหลือ {after} จาก {before}")
    if after:
        import re
        for m in re.finditer("ฝาก", s):
            print("    ตกค้าง …" + s[max(0, m.start()-40):m.end()+40].replace("\n", " ") + "…")


if __name__ == "__main__":
    main()
